"""Emit a per-sport discovery log from stored payloads.

Reports the status ``type``/``code`` values and statistics ``key``s actually
observed, so schema drift is easy to spot. Writes ``docs/discovery-log.md``.

Usage: python scripts/discovery_log.py
"""
from __future__ import annotations

import json
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from sport_scraper.config import DB_PATH  # noqa: E402


def stat_keys(stats_payload: dict) -> set[str]:
    keys: set[str] = set()
    for period in stats_payload.get("statistics") or []:
        if not isinstance(period, dict):
            continue
        for group in period.get("groups") or []:
            if not isinstance(group, dict):
                continue
            for item in group.get("statisticsItems") or []:
                if isinstance(item, dict) and item.get("key"):
                    keys.add(item["key"])
    return keys


def main() -> int:
    con = sqlite3.connect(DB_PATH)
    sport_of: dict[str, str] = {}
    status_types: dict[str, set[str]] = defaultdict(set)
    status_codes: dict[str, set[str]] = defaultdict(set)

    for ss_id, sport, data in con.execute("SELECT ss_id, sport, data FROM events"):
        sport_of[ss_id] = sport
        try:
            ev = json.loads(data)
        except ValueError:
            continue
        status = ev.get("status") or {}
        if status.get("type"):
            status_types[sport].add(status["type"])
        if status.get("code") is not None:
            status_codes[sport].add(str(status["code"]))

    stat_keys_by_sport: dict[str, set[str]] = defaultdict(set)
    matched: dict[str, int] = defaultdict(int)
    for ss_id, data in con.execute("SELECT ss_id, data FROM statistics"):
        sport = sport_of.get(ss_id)
        if not sport:
            continue
        try:
            payload = json.loads(data)
        except ValueError:
            continue
        keys = stat_keys(payload)
        if keys:
            stat_keys_by_sport[sport] |= keys
            matched[sport] += 1
    con.close()

    sports = sorted(set(sport_of.values()))
    lines = ["# Discovery log", "",
             "Observed upstream values, generated by `scripts/discovery_log.py`.", ""]
    for sport in sports:
        lines.append(f"## {sport}")
        lines.append("")
        lines.append(f"- status types: {', '.join(sorted(status_types[sport])) or '(none)'}")
        lines.append(f"- status codes: {', '.join(sorted(status_codes[sport])) or '(none)'}")
        keys = ", ".join(sorted(stat_keys_by_sport[sport])) or "(none captured)"
        lines.append(f"- statistic keys ({matched[sport]} payloads): {keys}")
        lines.append("")

    out = Path("docs/discovery-log.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out}")
    for sport in sports:
        print(f"  {sport}: types={len(status_types[sport])} "
              f"codes={len(status_codes[sport])} stat_keys={len(stat_keys_by_sport[sport])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
